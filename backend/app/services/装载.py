import json

from app.db import 连接, 写事务
from app.seed import 此刻
from app.services import 时间, 配对, 封印


def 装一批(体: dict) -> dict:
    """装载刷卡点：同卡进站开腿、出站成对；缺腿超时/孤儿旁路。

    口径（封印=版本追加）：
    - 进站：同卡若已有在途开腿 → 旧腿旁路(重复进站)并开新腿
    - 出站：匹配同卡在途开腿 → 写行程账并自动封印；若同键行程已存在（重放）
      → 封印只读：一致命中 / 冲突拒绝入旁路，绝不覆盖旧行
    - 批次末：按本批最大事件时扫缺腿超时
    - 整批在一个 IMMEDIATE 事务内：与封印写闸串行，不交错覆盖。
    """
    批次编号 = 体.get("批次编号") or f"批-{此刻().replace(':', '').replace('-', '')}"
    事件列表 = 体.get("事件") or []
    conn = 连接(自动提交=True)
    try:
        报告 = {
            "批次编号": 批次编号,
            "入流": 0,
            "开腿": 0,
            "成对": 0,
            "旁路": 0,
            "超时旁路": 0,
            "重放命中": 0,
            "重放拒绝": 0,
            "明细": [],
        }
        with 写事务(conn):
            站 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
            最大行程秒 = int(站.get("最大行程秒", "7200"))
            水位 = None

            for ev in 事件列表:
                事件编号 = ev["事件编号"]
                卡号 = ev["卡号"]
                站点键 = ev["站点键"]
                方向 = ev["方向"]
                事件时 = ev["事件时"]
                处理时 = ev.get("处理时") or 此刻()

                if 水位 is None or 时间.解析(事件时) > 时间.解析(水位):
                    水位 = 事件时

                if conn.execute("SELECT 1 FROM 刷卡点 WHERE 事件编号=?", (事件编号,)).fetchone():
                    # 已有刷卡点：内容一致 → 幂等跳过；内容分歧 → 封印重放隔离，绝不覆盖旧行
                    旧刷 = conn.execute(
                        "SELECT * FROM 刷卡点 WHERE 事件编号=?", (事件编号,)
                    ).fetchone()
                    一致 = (
                        旧刷["卡号"] == 卡号
                        and 旧刷["站点键"] == 站点键
                        and 旧刷["方向"] == 方向
                        and 旧刷["事件时"] == 事件时
                    )
                    if 一致:
                        报告["明细"].append({"事件编号": 事件编号, "命运": "幂等跳过"})
                        continue
                    if 旧刷["行程键"] and 旧刷["方向"] == "出站":
                        # 已物化行程的「出站」重放：走封印只读重放（一致命中/冲突拒绝）
                        结果 = 封印._重放内(
                            conn, 旧刷["行程键"], 站点键, 事件时, f"装载重放:{批次编号}"
                        )
                        if 结果.get("命中"):
                            报告["重放命中"] += 1
                            报告["明细"].append(
                                {"事件编号": 事件编号, "命运": "重放命中", "行程键": 旧刷["行程键"]}
                            )
                        elif 结果.get("接受"):
                            # 未封印路径下走版本追加：有版本链即可接受
                            报告["明细"].append(
                                {
                                    "事件编号": 事件编号,
                                    "命运": "重放追加版本",
                                    "行程键": 旧刷["行程键"],
                                    "当前版本": 结果.get("当前版本"),
                                }
                            )
                        else:
                            报告["重放拒绝"] += 1
                            报告["旁路"] += 1
                            报告["明细"].append(
                                {
                                    "事件编号": 事件编号,
                                    "命运": "重放拒绝",
                                    "行程键": 旧刷["行程键"],
                                    "拒绝": 结果.get("拒绝"),
                                }
                            )
                        continue
                    # 尚未成对却内容分歧：不得盖写，落旁路留证
                    conn.execute(
                        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                        (
                            "刷卡点重放冲突",
                            卡号,
                            事件编号,
                            json.dumps(
                                {"旧": dict(旧刷), "新": ev}, ensure_ascii=False
                            ),
                            处理时,
                        ),
                    )
                    报告["旁路"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-重放冲突"})
                    continue

                站行 = conn.execute("SELECT * FROM 站点 WHERE 站点键=?", (站点键,)).fetchone()
                if not 站行:
                    conn.execute(
                        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                        ("未知站点", 卡号, 事件编号, json.dumps(ev, ensure_ascii=False), 处理时),
                    )
                    conn.execute(
                        """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                           VALUES (?,?,?,?,?,?, '已旁路', '', ?)""",
                        (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                    )
                    报告["旁路"] += 1
                    报告["入流"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-未知站"})
                    continue

                if 方向 not in ("进站", "出站"):
                    conn.execute(
                        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                        ("方向非法", 卡号, 事件编号, json.dumps(ev, ensure_ascii=False), 处理时),
                    )
                    conn.execute(
                        """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                           VALUES (?,?,?,?,?,?, '已旁路', '', ?)""",
                        (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                    )
                    报告["旁路"] += 1
                    报告["入流"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-方向非法"})
                    continue

                conn.execute(
                    """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                       VALUES (?,?,?,?,?,?, '已入流', '', ?)""",
                    (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                )
                报告["入流"] += 1

                if 方向 == "进站":
                    旧 = conn.execute(
                        "SELECT * FROM 开腿账 WHERE 卡号=? AND 状态='在途'", (卡号,)
                    ).fetchone()
                    if 旧:
                        conn.execute(
                            "UPDATE 开腿账 SET 状态='已旁路', 更新处理时=? WHERE 开腿键=?",
                            (处理时, 旧["开腿键"]),
                        )
                        conn.execute(
                            "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=?",
                            ("已旁路", 旧["进站事件编号"]),
                        )
                        conn.execute(
                            "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                            (
                                "重复进站",
                                卡号,
                                旧["进站事件编号"],
                                json.dumps(
                                    {"旧开腿": 旧["开腿键"], "新进站": 事件编号},
                                    ensure_ascii=False,
                                ),
                                处理时,
                            ),
                        )
                        报告["旁路"] += 1
                        报告["明细"].append(
                            {"事件编号": 旧["进站事件编号"], "命运": "旁路-重复进站"}
                        )

                    开腿键 = f"腿-{事件编号}"
                    conn.execute(
                        """INSERT INTO 开腿账(开腿键,卡号,进站事件编号,进站站点键,进站事件时,状态,更新处理时)
                           VALUES (?,?,?,?,?,'在途',?)""",
                        (开腿键, 卡号, 事件编号, 站点键, 事件时, 处理时),
                    )
                    conn.execute(
                        "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=?",
                        ("已开腿", 事件编号),
                    )
                    报告["开腿"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "已开腿", "开腿键": 开腿键})
                else:
                    开腿 = conn.execute(
                        "SELECT * FROM 开腿账 WHERE 卡号=? AND 状态='在途' ORDER BY 进站事件时 ASC LIMIT 1",
                        (卡号,),
                    ).fetchone()
                    if not 开腿:
                        conn.execute(
                            "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=?",
                            ("已旁路", 事件编号),
                        )
                        conn.execute(
                            "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                            (
                                "出站孤儿",
                                卡号,
                                事件编号,
                                json.dumps(ev, ensure_ascii=False),
                                处理时,
                            ),
                        )
                        报告["旁路"] += 1
                        报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-出站孤儿"})
                        continue

                    结果 = 配对.成对写出站(
                        conn, 开腿, 事件编号, 站点键, 事件时, 处理时
                    )
                    行程键 = 结果["行程键"]
                    if 结果["动作"] == "新建":
                        报告["成对"] += 1
                        报告["明细"].append(
                            {"事件编号": 事件编号, "命运": "已成对", "行程键": 行程键}
                        )
                    elif 结果["动作"] == "重放命中":
                        # 封印行程只读：只对齐刷卡点/开腿态，绝不改行程行
                        conn.execute(
                            "UPDATE 刷卡点 SET 命运='已成对', 行程键=? WHERE 事件编号 IN (?,?)",
                            (行程键, 开腿["进站事件编号"], 事件编号),
                        )
                        conn.execute(
                            "UPDATE 开腿账 SET 状态='已成对', 更新处理时=? WHERE 开腿键=?",
                            (处理时, 开腿["开腿键"]),
                        )
                        报告["重放命中"] += 1
                        报告["明细"].append(
                            {"事件编号": 事件编号, "命运": "重放命中", "行程键": 行程键}
                        )
                    else:
                        报告["重放拒绝"] += 1
                        报告["旁路"] += 1
                        # 重放冲突：出站刷卡点标旁路，开腿原样未动（基行不可覆盖）
                        conn.execute(
                            "UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?",
                            (事件编号,),
                        )
                        报告["明细"].append(
                            {
                                "事件编号": 事件编号,
                                "命运": "重放拒绝",
                                "行程键": 行程键,
                                "拒绝": 结果.get("拒绝"),
                            }
                        )

            if 水位:
                报告["超时旁路"] = 配对.扫缺腿超时(conn, 最大行程秒, 水位, 此刻())
                报告["旁路"] += 报告["超时旁路"]

            # 批次编号幂等：同一批次重复装载只保留首条报告
            conn.execute(
                "INSERT OR IGNORE INTO 装载批次(编号, 时刻, 报告) VALUES (?,?,?)",
                (批次编号, 此刻(), json.dumps(报告, ensure_ascii=False)),
            )
        return 报告
    finally:
        conn.close()
